-- Disposable PostgreSQL 17 schema used only by CI to exercise the P2 migration.
-- This is a targeted fixture, not a full substitute for an isolated Supabase branch.
create schema if not exists auth;
create role anon nologin;
create role authenticated nologin;

create or replace function auth.uid() returns uuid
language sql stable
as $$
  select coalesce(
    nullif(current_setting('request.jwt.claim.sub', true), ''),
    nullif(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub', '')
  )::uuid
$$;

grant usage on schema public, auth to anon, authenticated;
grant execute on function auth.uid() to authenticated;

create table public.profiles (
  id uuid primary key,
  role text not null default 'user',
  email text
);
alter table public.profiles enable row level security;
create policy "Users can view own profile"
  on public.profiles for select to authenticated
  using (auth.uid() = id);
grant select (id, role) on public.profiles to authenticated;

create table public.stores (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  website_url text,
  affiliate_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint stores_slug_format check (
    slug = lower(slug) and slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
  )
);

create table public.promo_codes (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  code text not null,
  title text,
  description text,
  destination_url text not null,
  expires_at timestamptz,
  approved boolean not null default false,
  is_active boolean not null default true,
  click_count bigint not null default 0 check (click_count >= 0),
  worked_count int not null default 0 check (worked_count >= 0),
  failed_count int not null default 0 check (failed_count >= 0),
  submitted_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id,code)
);
create table public.promo_votes (
  id uuid primary key default gen_random_uuid(),
  promo_id uuid not null references public.promo_codes(id) on delete cascade,
  vote_type text not null check (vote_type in ('worked','failed')),
  fingerprint text not null,
  created_at timestamptz not null default now(),
  unique (promo_id,fingerprint)
);
create table public.promo_clicks (
  id bigint generated by default as identity primary key,
  promo_id uuid not null references public.promo_codes(id) on delete cascade,
  fingerprint text,
  created_at timestamptz not null default now()
);

alter table public.stores enable row level security;
alter table public.promo_codes enable row level security;
alter table public.promo_votes enable row level security;
alter table public.promo_clicks enable row level security;

create policy "Anonymous read active stores"
  on public.stores for select to anon using (is_active = true);
create policy "Readable stores"
  on public.stores for select to authenticated
  using (is_active = true or exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  ));

create policy "Anonymous read live promos"
  on public.promo_codes for select to anon
  using (
    approved = true and is_active = true
    and (expires_at is null or expires_at > now())
  );
create policy "Readable promos"
  on public.promo_codes for select to authenticated
  using (
    (approved = true and is_active = true
      and (expires_at is null or expires_at > now()))
    or exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role = 'admin'
    )
  );
create policy "Admins update promos"
  on public.promo_codes for update to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  ));
create policy "Admins delete promos"
  on public.promo_codes for delete to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  ));
create policy "Submit or admin insert promos"
  on public.promo_codes for insert to authenticated
  with check (
    (submitted_by = auth.uid() and approved = false)
    or exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role = 'admin'
    )
  );

grant select (id,slug,name,is_active) on public.stores to anon,authenticated;
grant select (id,store_id,code,title,description,expires_at,approved,is_active,
  click_count,worked_count,failed_count,created_at,updated_at)
  on public.promo_codes to anon,authenticated;


-- Fixture admin permissions and insert grants for the isolated P2 lifecycle test.
create policy "Admins insert stores" on public.stores
  for insert to authenticated
  with check (exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  ));

create policy "Admins update stores" on public.stores
  for update to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  ))
  with check (exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  ));

grant insert (name,slug,website_url,affiliate_url,is_active),
  update (is_active) on public.stores to authenticated;
grant insert (store_id,code,title,description,destination_url,expires_at,submitted_by),
  update (approved,is_active) on public.promo_codes to authenticated;
